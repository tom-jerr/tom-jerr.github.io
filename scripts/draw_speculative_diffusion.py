class Figure:
    def __init__(self, title, desc, height):
        self.height = height
        self.parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{height}" viewBox="0 0 {W} {height}" role="img" aria-labelledby="title desc">',
                      f'<title id="title">{escape(title)}</title><desc id="desc">{escape(desc)}</desc>',
                      f'<style>text{{font-family:{FONT};fill:{INK}}}</style>',
                      f'<defs><marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto"><path d="M0 0L10 5L0 10Z" fill="{INK}"/></marker></defs>',
                      f'<rect width="{W}" height="{height}" fill="white"/>']
        self.text(32, 39, title, 26, weight=700)

    def text(self, x, y, text, size=20, color=INK, anchor="start", weight=400):
        self.parts.append(f'<text x="{x}" y="{y}" font-size="{size}" style="fill:{color}" text-anchor="{anchor}" font-weight="{weight}">{escape(text)}</text>')

    def rect(self, x, y, w, h, kind="neutral", dashed=False, radius=10):
        fill, stroke = COLORS[kind]
        dash = ' stroke-dasharray="5 5"' if dashed else ""
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="{stroke}" stroke-width="1.5"{dash}/>')

    def box(self, x, y, title, lines=(), kind="neutral", w=240, h=112):
        self.rect(x, y, w, h, kind)
        self.text(x + w / 2, y + 32, title, 22, anchor="middle", weight=650)
        for i, line in enumerate(lines):
            self.text(x + w / 2, y + 62 + 25 * i, line, 19, anchor="middle")

    def arrow(self, *points, dashed=False):
        d = "M" + " L".join(f"{x},{y}" for x, y in points)
        dash = ' stroke-dasharray="5 5"' if dashed else ""
        self.parts.append(f'<path d="{d}" fill="none" stroke="{INK}" stroke-width="1.6" stroke-linejoin="round" marker-end="url(#arrow)"{dash}/>')

    def chain(self, y, xs=XS, width=240):
        for left, right in zip(xs, xs[1:]):
            self.arrow((left + width, y), (right - 5, y))

    def tokens(self, x, y, labels, kinds=None, size=44, gap=10):
        for i, label in enumerate(labels):
            k = kinds[i] if kinds else "neutral"
            self.rect(x + i * (size + gap), y, size, 40, k, radius=6)
            self.text(x + i * (size + gap) + size / 2, y + 27, label, 20, anchor="middle", weight=600)

    def note(self, y, text):
        self.text(32, y, text, 19, MUTED)

    def finish(self):
        return "\n".join(self.parts + ["</svg>\n"])


