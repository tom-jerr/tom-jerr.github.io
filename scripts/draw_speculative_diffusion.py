def dflash2_inference():
    f = Figure("DFlash 2 推理：先并行打分，再走一条候选路径", "带卷积 backbone 一次生成 unary logits；邻接候选对并行评分；从 anchor 出发因果 walk，只有选出的一条链送入 target。", 630)
    f.chain(179)
    f.box(32, 123, "带卷积的 draft", ["一次 block forward", "hidden 局部混合也并行"], "draft")
    f.box(304, 123, "保留候选", ["每个位置 unary top-K", "候选集合已经确定"], "neutral")
    f.box(576, 123, "并行邻接评分", ["基础分数 + 前驱匹配", "不再执行 backbone"], "seq")
    f.box(848, 123, "因果 walk → verify", ["按已选前驱选下一词", "target 只验证一条链"], "target")
    f.text(32, 286, "候选示意", 20, weight=650)
    f.text(172, 286, "为便于阅读仅画 K=3、3 个位置；连线为已预计算的候选对，粗线为所选路径。", 18, MUTED)
    cx = [330, 536, 742]
    ys = [323, 383, 443]
    # Candidate-pair edges are behind node faces. Emphasize the causal path.
    for a, b in zip(cx, cx[1:]):
        for ya in ys:
            for yb in ys:
                f.parts.append(f'<path d="M{a+86},{ya+20} L{b},{yb+20}" stroke="{LINE}" stroke-width="1" fill="none"/>')
    f.tokens(82, 383, ["D"], ["anchor"], size=60)
    for yy in ys:
        f.parts.append(f'<path d="M142,403 L330,{yy+20}" stroke="{LINE}" stroke-width="1" fill="none"/>')
    for (x1,y1),(x2,y2) in [((142,403),(330,403)),((416,403),(536,343)),((622,343),(742,403))]:
        f.parts.append(f'<path d="M{x1},{y1} L{x2},{y2}" stroke="#7656D8" stroke-width="3.5" fill="none" marker-end="url(#arrow)"/>')
    for j, x in enumerate(cx):
        f.text(x+43, 315, f"位置 {j+1}", 18, anchor="middle")
        for k, y in enumerate(ys):
            selected = k == [1,0,1][j]
            f.tokens(x, y, [f"{['E','F','G'][j]}{k+1}"], ["seq" if selected else "neutral"], size=86)
    f.text(871, 362, "所选链", 20, weight=650)
    f.text(871, 399, "E2 → F1 → G2", 21)
    f.text(871, 435, "随链保存实际 q", 19)
    f.text(871, 471, "step 0 前驱 = anchor", 17)
    f.text(871, 497, "greedy：argmax，q=one-hot", 17)
    f.text(871, 523, "T>0：逆 CDF 采样，q = 行概率", 17)
    f.note(565, "这里是逐步 greedy / sampling walk，不是 Viterbi 全局最优路径，也不是 target 验证整张候选树。")
    f.note(601, "候选外 proposal q = 0；随机拒绝后的残差采样仍可输出 top-K 以外的 target token。")
    return f


